import numpy as np

"""
REL-55 — Closure / irreducibility selection audit

Question:
Can irreducibility be interpreted as a closure condition rather than an
independent aesthetic/minimality axiom?

We compare one irreducible 4-component Clifford module with duplicated
modules S_4 ⊕ S_4. Both reproduce the same local Clifford dynamics, but the
duplicated module contains nontrivial internal operators commuting with all
gamma matrices. Those operators mix the duplicate sectors without changing
the Clifford action. This is an explicit witness of unused internal freedom.

The audit deliberately distinguishes:
  1. algebraic irreducibility of the Clifford action;
  2. dynamical closure under the Clifford generators;
  3. the stronger claim that Ω itself derives irreducibility.

The numerical experiment supports (1)->(2) and exposes the extra freedom in
reducible duplication. It does NOT by itself derive (1) from Ω.
"""

rng = np.random.default_rng(55)
I2 = np.eye(2, dtype=complex)
I4 = np.eye(4, dtype=complex)

s1 = np.array([[0, 1], [1, 0]], dtype=complex)
s2 = np.array([[0, -1j], [1j, 0]], dtype=complex)
s3 = np.array([[1, 0], [0, -1]], dtype=complex)
pauli = [s1, s2, s3]

# 3+1D Dirac Hamiltonian representation from REL-49.
alpha = [np.kron(s, s1) for s in pauli]
beta = np.kron(I2, s3)
gamma_set = alpha + [beta]

# Irreducible 4-component module: solve the commutant numerically by using
# the singular values of the stacked commutator map X -> [X,G].
def commutant_singular_values(gens):
    n = gens[0].shape[0]
    blocks = []
    for G in gens:
        # vec(XG-GX) = (G^T ⊗ I - I ⊗ G) vec(X)
        blocks.append(np.kron(G.T, np.eye(n)) - np.kron(np.eye(n), G))
    A = np.vstack(blocks)
    return np.linalg.svd(A, compute_uv=False)

sv4 = commutant_singular_values(gamma_set)
rank_tol = 1e-10
commutant_dim4 = int(np.sum(sv4 < rank_tol))

# Duplicated module S4 ⊕ S4.
gamma8 = [np.block([[G, np.zeros_like(G)], [np.zeros_like(G), G]]) for G in gamma_set]
sv8 = commutant_singular_values(gamma8)
commutant_dim8 = int(np.sum(sv8 < rank_tol))

# Explicit nontrivial sector-mixing operator X = sigma_1 ⊗ I4.
Xmix = np.kron(s1, I4)
max_commutator_mix = max(np.linalg.norm(Xmix @ G - G @ Xmix) for G in gamma8)

# Xmix is not proportional to identity, so it is genuine internal freedom.
identity8 = np.eye(8, dtype=complex)
non_scalar_mix_norm = np.linalg.norm(Xmix - np.trace(Xmix) / 8 * identity8)

# Closure test: generic Clifford evolution generated by the gamma set cannot
# distinguish the two duplicate sectors because Xmix commutes with every
# generator. Hence an internal transformation survives all local Clifford
# relations. We also verify the same dispersion in both copies.
max_dispersion_gap = 0.0
for _ in range(100):
    p = rng.normal(size=3)
    m = abs(rng.normal())
    H4 = sum(p[i] * alpha[i] for i in range(3)) + m * beta
    H8 = np.block([[H4, np.zeros((4, 4), dtype=complex)],
                   [np.zeros((4, 4), dtype=complex), H4]])
    e4 = np.sort(np.linalg.eigvalsh(H4))
    e8 = np.sort(np.linalg.eigvalsh(H8))
    target8 = np.repeat(e4, 2)
    max_dispersion_gap = max(max_dispersion_gap,
                             np.max(np.abs(e8 - target8)))

print(f"commutant_dim_4={commutant_dim4}")
print(f"commutant_dim_8={commutant_dim8}")
print(f"max_commutator_mix={max_commutator_mix:.17g}")
print(f"non_scalar_mix_norm={non_scalar_mix_norm:.17g}")
print(f"max_dispersion_gap={max_dispersion_gap:.17g}")

assert commutant_dim4 == 1
assert commutant_dim8 == 4
assert max_commutator_mix < 1e-14
assert non_scalar_mix_norm > 1.0
assert max_dispersion_gap < 1e-12

print("RESULT: irreducible Clifford module has scalar commutant; duplicated module has nontrivial sector-mixing freedom.")
print("BOUNDARY: closure/irreducibility is not yet derived from Omega primitives alone.")
